// macOS key codes (Carbon kVK_*) to the Windows virtual-key codes the rest of the
// app uses. Pure, so it can be tested on Windows.
import { VK } from '../../shared/keys'

// Letters, digits and punctuation by position on an ANSI keyboard.
const LETTERS = 'ASDFHGZXCV?BQWERYT'
const KEYS: Record<number, number> = {
  0x0a: 0xc0, // § / ` on ISO keyboards
  0x12: 0x31, 0x13: 0x32, 0x14: 0x33, 0x15: 0x34, 0x16: 0x36, 0x17: 0x35,
  0x18: 0xbb, 0x19: 0x39, 0x1a: 0x37, 0x1b: 0xbd, 0x1c: 0x38, 0x1d: 0x30,
  0x1e: 0xdd, 0x1f: 0x4f, 0x20: 0x55, 0x21: 0xdb, 0x22: 0x49, 0x23: 0x50,
  0x24: VK.Enter, 0x25: 0x4c, 0x26: 0x4a, 0x27: 0xde, 0x28: 0x4b, 0x29: 0xba,
  0x2a: 0xdc, 0x2b: 0xbc, 0x2c: 0xbf, 0x2d: 0x4e, 0x2e: 0x4d, 0x2f: 0xbe,
  0x30: VK.Tab, 0x31: VK.Space, 0x32: 0xc0, 0x33: VK.Backspace, 0x35: VK.Escape,
  // keypad
  0x41: 0x6e, 0x43: 0x6a, 0x45: 0x6b, 0x4b: 0x6f, 0x4c: VK.Enter, 0x4e: 0x6d,
  0x52: 0x60, 0x53: 0x61, 0x54: 0x62, 0x55: 0x63, 0x56: 0x64, 0x57: 0x65, 0x58: 0x66, 0x59: 0x67, 0x5b: 0x68, 0x5c: 0x69,
  // function keys
  0x7a: 0x70, 0x78: 0x71, 0x63: 0x72, 0x76: 0x73, 0x60: 0x74, 0x61: 0x75, 0x62: 0x76, 0x64: 0x77,
  0x65: 0x78, 0x6d: 0x79, 0x67: 0x7a, 0x6f: 0x7b, 0x69: 0x7c, 0x6b: 0x7d, 0x71: 0x7e, 0x6a: 0x7f,
  0x40: 0x80, 0x4f: 0x81, 0x50: 0x82, 0x5a: 0x83,
  // navigation
  0x73: 0x24, 0x74: 0x21, 0x75: 0x2e, 0x77: 0x23, 0x79: 0x22, 0x7b: 0x25, 0x7c: 0x27, 0x7d: 0x28, 0x7e: 0x26,
  0xb3: VK.Fn // 🌐 on some keyboards arrives as a key of its own
}
for (let i = 0; i < LETTERS.length; i++) if (LETTERS[i] !== '?') KEYS[i] = LETTERS.charCodeAt(i)

// Modifiers arrive as flagsChanged events; whether the key went down or up is in
// the flags, whose device bits tell left from right.
const MODIFIERS: Record<number, [vk: number, mask: number]> = {
  0x38: [VK.LShift, 0x02],
  0x3c: [VK.RShift, 0x04],
  0x3b: [VK.LCtrl, 0x01],
  0x3e: [VK.RCtrl, 0x2000],
  0x3a: [VK.LAlt, 0x20],
  0x3d: [VK.RAlt, 0x40],
  0x37: [VK.LWin, 0x08],
  0x36: [VK.RWin, 0x10]
}
const FN_KEY = 0x3f
const CAPS_LOCK = 0x39
export const FLAG_FN = 0x800000 // kCGEventFlagMaskSecondaryFn

export interface KeyEvent {
  vk: number
  down: boolean
}

export function createMacKeyDecoder() {
  let fnDown = false
  const fn = (down: boolean): KeyEvent[] => {
    if (down === fnDown) return [] // 🌐 can arrive both as a flag change and as a key
    fnDown = down
    return [{ vk: VK.Fn, down }]
  }
  return {
    // keyDown / keyUp
    key(code: number, down: boolean): KeyEvent[] {
      const vk = KEYS[code]
      if (vk === VK.Fn) return fn(down)
      return vk === undefined ? [] : [{ vk, down }]
    },
    flagsChanged(code: number, flags: number): KeyEvent[] {
      const mod = MODIFIERS[code]
      if (mod) return [{ vk: mod[0], down: (flags & mod[1]) !== 0 }]
      if (code === CAPS_LOCK) return [{ vk: 0x14, down: true }, { vk: 0x14, down: false }] // toggles: one tap
      if (code === FN_KEY || code === 0xb3 || Boolean(flags & FLAG_FN) !== fnDown) return fn((flags & FLAG_FN) !== 0)
      return []
    }
  }
}
